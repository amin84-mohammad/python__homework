# Arithmetic Operations Without Variables

print(2 + 2)
print(8 - 3)
print(4 * 5)
print(20 / 4)
print(15 % 4)


# Arithmetic Operations With Variables

a = 10
b = 5

print(a + b)
print(a - b)
print(a * b)
print(a / b)
print(a % b)


# Comparison Operators Without Variables

print(5 > 3)
print(2 < 7)
print(4 == 4)
print(6 != 2)
print(8 >= 8)


# Comparison Operators With Variables

x = 12
y = 8

print(x > y)
print(x < y)
print(x == y)
print(x != y)
print(x >= y)
